import { memo } from 'react'
import { SPECIES_IDS, type Species } from '../session'
import { paint } from './cubes'
import { buffalo, can, egret, meadow, plot, pond, rocks, small } from './decor'
import { buildPet, PET_IDS, PETS, type PetId, partsOf } from './pets'
import { buildTree, SPECIES } from './trees'

type Frame = { x: number; y: number; w: number; h: number; scale: number }

const TREE_FRAME: Frame = { x: -60, y: -100, w: 120, h: 132, scale: 5 }
const PET_FRAME: Frame = { x: -36, y: -46, w: 72, h: 62, scale: 6 }
const TREE_CUBE = 2 // A tree cube is half a plot cube.

function image(frame: Frame, draw: (ctx: CanvasRenderingContext2D) => void) {
  const c = document.createElement('canvas')
  c.width = frame.w * frame.scale
  c.height = frame.h * frame.scale
  const ctx = c.getContext('2d') as CanvasRenderingContext2D
  ctx.scale(frame.scale, frame.scale)
  ctx.translate(-frame.x, -frame.y)
  draw(ctx)
  return `<image href="${c.toDataURL('image/png')}" x="${frame.x}" y="${frame.y}" width="${frame.w}" height="${frame.h}"/>`
}

function treeArt(id: Species, stage: number) {
  return image(TREE_FRAME, (ctx) => {
    // A soft shadow falls away from the light, onto the grass.
    const R = [12, 15, 21, Math.min(SPECIES[id].shadow * 0.82, 30)][stage]
    ctx.save()
    // Clipped to the plot, so a shadow never lands on the sky at the edge of the garden.
    ctx.beginPath()
    ctx.moveTo(0, -16)
    ctx.lineTo(32, 0)
    ctx.lineTo(0, 16)
    ctx.lineTo(-32, 0)
    ctx.closePath()
    ctx.clip()
    ctx.translate(R * 0.24, R * 0.1)
    ctx.scale(1, 0.5)
    const grad = ctx.createRadialGradient(0, 0, R * 0.2, 0, 0, R)
    grad.addColorStop(0, 'rgba(18,46,28,.46)')
    grad.addColorStop(0.7, 'rgba(18,46,28,.26)')
    grad.addColorStop(1, 'rgba(18,46,28,0)')
    ctx.fillStyle = grad
    ctx.beginPath()
    ctx.arc(0, 0, R, 0, 6.3)
    ctx.fill()
    ctx.restore()
    paint(ctx, buildTree(id, stage), TREE_CUBE)
  })
}

function petArt(id: PetId) {
  const base = image(PET_FRAME, (ctx) => {
    ctx.translate(3, 2)
    ctx.scale(1, 0.5)
    const grad = ctx.createRadialGradient(0, 0, 3, 0, 0, 17)
    grad.addColorStop(0, 'rgba(18,46,28,.42)')
    grad.addColorStop(1, 'rgba(18,46,28,0)')
    ctx.fillStyle = grad
    ctx.beginPath()
    ctx.arc(0, 0, 17, 0, 6.3)
    ctx.fill()
  })
  const parts = buildPet(id)
  return (
    `<g id="pet-${id}-base">${base}</g>` +
    partsOf(id)
      .map(
        (k) =>
          `<g id="pet-${id}-${k}">${image(PET_FRAME, (ctx) => paint(ctx, parts[k], PETS[id].tu))}</g>`,
      )
      .join('')
  )
}

function buildAll() {
  const trees = SPECIES_IDS.flatMap((id) =>
    [0, 1, 2, 3].map((st) => `<g id="tree-${id}-${st}">${treeArt(id, st)}</g>`),
  )
  const plots = [0, 1, 2, 3].map((v) => `<g id="plot-${v}">${plot(v)}</g>`)
  const decor = `<g id="pond-ground">${pond()}</g><g id="egret">${small(egret(), 3.1, -2.6)}</g><g id="rocks">${rocks()}</g><g id="meadow">${meadow()}</g><g id="buffalo">${buffalo()}</g><g id="can">${can()}</g>`
  return [...trees, ...plots, decor, ...PET_IDS.map(petArt)].join('')
}

let markup: string | null = null

// Each grid is painted once to an image, and the garden and Work view reuse them through <use>.
export const Sprites = memo(function Sprites() {
  markup ??= buildAll()
  return (
    <svg width="0" height="0" style={{ position: 'absolute' }} aria-hidden="true">
      {/* biome-ignore lint/security/noDangerouslySetInnerHtml: markup is generated by this app, with no outside input */}
      <defs dangerouslySetInnerHTML={{ __html: markup }} />
    </svg>
  )
})
